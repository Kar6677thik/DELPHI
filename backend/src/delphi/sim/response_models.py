"""The simulator's truth about how customers answer probes (docs/14 §5, FR-SIM-03).

The answer distributions are deliberately not the KB's likelihoods (docs/14 §1 rule 3): each is
a Dirichlet perturbation of the KB v1 row, drawn once with a fixed seed and frozen into
``config/response_models.generated.yaml``. Freezing is a pure function of KB v1 and
``config/response_models.yaml``; a snapshot test keeps the committed file in step.
"""

from __future__ import annotations

import math
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np
import yaml
from pydantic import BaseModel, ConfigDict, Field

from delphi.kb.canonical import content_sha256
from delphi.kb.model import KnowledgeBase
from delphi.sim.rng import keyed_rng
from delphi.sim.scenarios import GENUINE_REFERENCE, SCENARIO_HYPOTHESIS, ScenarioType

CONFIG_DIR = Path(__file__).resolve().parent / "config"
CONFIG_FILE = CONFIG_DIR / "response_models.yaml"
GENERATED_FILE = CONFIG_DIR / "response_models.generated.yaml"

Probs = tuple[float, ...]
_HEADER = (
    "# GENERATED by `uv run delphi sim freeze-response-models` from KB v1 and\n"
    "# response_models.yaml (docs/14 §5.2). Do not edit: change the inputs and regenerate.\n"
)


# --------------------------------------------------------------------------- configuration


class _Frozen(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


class TelemetryTargets(_Frozen):
    """Approximate rates of the telemetry-driven passive outcomes (docs/14 §5.1)."""

    on_call_unknown_number: float = Field(ge=0, le=1)
    remote_access_active: float = Field(ge=0, le=1)
    paste_or_long_dwell: float = Field(ge=0, le=1)
    cadence_mismatch: float = Field(ge=0, le=1)


class CoachedVictims(_Frozen):
    share: float = Field(ge=0, le=1)
    genuine_weight: float = Field(ge=0, le=1)
    scenarios: tuple[ScenarioType, ...]
    probes: tuple[str, ...]


class CoachingAdaptation(_Frozen):
    """Moves one scenario's answers to one probe toward the GENUINE row (docs/14 §5.3)."""

    scenario: ScenarioType
    probe: str
    start_day: float = Field(ge=0)
    # docs/14 §5.3's example: the DA spell-breaker loses half its signal over 14 days.
    ramp_days: float = Field(default=14, gt=0)
    shift: float = Field(ge=0, le=1)

    def weight(self, sim_day: float) -> float:
        progress = (sim_day - self.start_day) / self.ramp_days
        return self.shift * min(max(progress, 0.0), 1.0)


class ResponseModelConfig(_Frozen):
    generator_version: int = Field(ge=1)
    freeze_seed: int = Field(ge=0)
    concentration: float = Field(gt=0)
    perturbed_evidence: tuple[str, ...]
    telemetry_targets: dict[ScenarioType, TelemetryTargets]
    coached_victims: CoachedVictims
    pinned_outcomes: dict[ScenarioType, dict[str, dict[str, float]]]
    explicit_answers: dict[ScenarioType, dict[str, Probs]]
    coaching_adaptation: tuple[CoachingAdaptation, ...] = ()


def load_config(path: Path = CONFIG_FILE) -> ResponseModelConfig:
    return ResponseModelConfig.model_validate(yaml.safe_load(path.read_text(encoding="utf-8")))


# --------------------------------------------------------------------------- the freeze


@dataclass(frozen=True, slots=True)
class FrozenAnswers:
    """The output of the freeze: what ``response_models.generated.yaml`` holds."""

    generator_version: int
    freeze_seed: int
    concentration: float
    kb_sha256: str
    outcomes: Mapping[str, tuple[str, ...]]
    answers: Mapping[ScenarioType, Mapping[str, Probs]]
    coached: Mapping[ScenarioType, Mapping[str, Probs]]


def answered_sources(kb: KnowledgeBase, config: ResponseModelConfig) -> tuple[str, ...]:
    """Every ACTIVE probe plus the perturbed evidence, in the KB's source order."""
    return tuple(
        s.key
        for s in kb.ordered_sources()
        if s.mode == "ACTIVE" or s.key in config.perturbed_evidence
    )


def _pin(probs: Probs, outcomes: tuple[str, ...], pinned: Mapping[str, float]) -> Probs:
    """Set the pinned outcomes; the others keep their proportions and share the rest."""
    rest = 1.0 - sum(pinned.values())
    free = sum(p for o, p in zip(outcomes, probs, strict=True) if o not in pinned)
    return tuple(
        pinned[o] if o in pinned else p * rest / free for o, p in zip(outcomes, probs, strict=True)
    )


def _mix(a: Probs, b: Probs, weight_a: float) -> Probs:
    return tuple(weight_a * x + (1.0 - weight_a) * y for x, y in zip(a, b, strict=True))


def row_rng(freeze_seed: int, scenario: ScenarioType, source: str) -> np.random.Generator:
    """The stream for one (scenario, source) row, derived from their names (docs/14 §5.2).

    Adding a scenario or a source later never changes the numbers already frozen.
    """
    return keyed_rng(freeze_seed, scenario.value, source)


# An explicit row's probabilities must sum to 1 within this tolerance.
_SUM_TOLERANCE = 1e-9


def validate_config(kb: KnowledgeBase, config: ResponseModelConfig) -> None:
    """Check the config against KB v1 before anything is drawn; raise one error listing every
    problem, so a typo never surfaces as a bare KeyError or a silently ignored setting."""
    sources = answered_sources(kb, config)
    problems: list[str] = []
    for scenario in ScenarioType:
        explicit = config.explicit_answers.get(scenario)
        hypothesis = SCENARIO_HYPOTHESIS[scenario]
        if explicit is None:
            if hypothesis not in kb.hypotheses:
                problems.append(f"{scenario}: {hypothesis} has no KB row and no explicit_answers")
            continue
        for key in sources:
            if key not in explicit:
                problems.append(f"{scenario}: explicit_answers has no {key} row")
        for key, probs in explicit.items():
            where = f"explicit_answers.{scenario}.{key}"
            if key not in sources:
                problems.append(f"{where}: not an answered source")
                continue
            if len(probs) != len(kb.sources[key].outcomes):
                outcomes = len(kb.sources[key].outcomes)
                problems.append(f"{where}: {len(probs)} values for {outcomes} outcomes")
            if min(probs) < 0 or not math.isclose(sum(probs), 1.0, abs_tol=_SUM_TOLERANCE):
                problems.append(f"{where}: not a distribution (sum {sum(probs)!r})")
    for scenario, rows in config.pinned_outcomes.items():
        for key, pins in rows.items():
            where = f"pinned_outcomes.{scenario}.{key}"
            if scenario in config.explicit_answers:
                problems.append(f"{where}: {scenario} has explicit answers, nothing is drawn")
            if key not in sources:
                problems.append(f"{where}: not an answered source")
                continue
            unknown = sorted(set(pins) - set(kb.sources[key].outcomes))
            if unknown:
                problems.append(f"{where}: unknown outcome(s) {', '.join(unknown)}")
            if min(pins.values()) < 0 or sum(pins.values()) >= 1:
                problems.append(f"{where}: pins must be ≥ 0 and sum below 1")
    for probe in config.coached_victims.probes:
        if probe not in sources:
            problems.append(f"coached_victims.probes: {probe} is not an answered source")
    if problems:
        raise ValueError("invalid response-model config:\n  " + "\n  ".join(problems))


def freeze(kb: KnowledgeBase, config: ResponseModelConfig) -> FrozenAnswers:
    """Draw the answer distributions (docs/14 §5.2). Deterministic in ``kb`` and ``config``.

    Scenarios listed in ``explicit_answers`` take those rows exactly; every other scenario
    draws each row from its KB v1 hypothesis. A missing row is an error, never a fallback.
    """
    validate_config(kb, config)
    sources = answered_sources(kb, config)
    answers: dict[ScenarioType, dict[str, Probs]] = {}
    for scenario in ScenarioType:
        hypothesis = SCENARIO_HYPOTHESIS[scenario]
        explicit = config.explicit_answers.get(scenario)
        rows: dict[str, Probs] = {}
        for key in sources:
            if explicit is not None:
                rows[key] = tuple(float(p) for p in explicit[key])
                continue
            kb_row = kb.hypotheses[hypothesis].likelihoods[key]
            alpha = config.concentration * np.asarray(kb_row.probs, dtype=np.float64)
            rng = row_rng(config.freeze_seed, scenario, key)
            drawn = tuple(float(p) for p in rng.dirichlet(alpha))
            pinned = config.pinned_outcomes.get(scenario, {}).get(key)
            rows[key] = _pin(drawn, kb.sources[key].outcomes, pinned) if pinned else drawn
        answers[scenario] = rows

    coached_cfg = config.coached_victims
    genuine = answers[GENUINE_REFERENCE]
    coached = {
        scenario: {
            probe: _mix(genuine[probe], answers[scenario][probe], coached_cfg.genuine_weight)
            for probe in coached_cfg.probes
        }
        for scenario in coached_cfg.scenarios
    }
    return FrozenAnswers(
        generator_version=config.generator_version,
        freeze_seed=config.freeze_seed,
        concentration=config.concentration,
        kb_sha256=content_sha256(kb),
        outcomes={key: kb.sources[key].outcomes for key in sources},
        answers=answers,
        coached=coached,
    )


def dump_yaml(frozen: FrozenAnswers) -> str:
    """Stable text: fixed key order, floats in round-trip repr form."""
    document: dict[str, Any] = {
        "generator_version": frozen.generator_version,
        "freeze_seed": frozen.freeze_seed,
        "concentration": frozen.concentration,
        "kb_sha256": frozen.kb_sha256,
        "outcomes": {k: list(v) for k, v in frozen.outcomes.items()},
        "answers": {
            s.value: {k: list(p) for k, p in rows.items()} for s, rows in frozen.answers.items()
        },
        "coached": {
            s.value: {k: list(p) for k, p in rows.items()} for s, rows in frozen.coached.items()
        },
    }
    body = yaml.safe_dump(document, sort_keys=False, default_flow_style=None, width=1000)
    return _HEADER + body


# --------------------------------------------------------------------------- runtime use


@dataclass(frozen=True, slots=True)
class ResponseModels:
    """The frozen answers plus the run-time switches, for the simulator to sample from."""

    outcomes: Mapping[str, tuple[str, ...]]
    answers: Mapping[ScenarioType, Mapping[str, Probs]]
    coached: Mapping[ScenarioType, Mapping[str, Probs]]
    telemetry_targets: Mapping[ScenarioType, TelemetryTargets]
    coached_share: float
    adaptations: tuple[CoachingAdaptation, ...]

    def answer_probs(
        self, scenario: ScenarioType, probe: str, *, coached: bool = False, sim_day: float = 0.0
    ) -> Probs:
        """P_true(· | s, a) in the probe's outcome order, after coaching and adaptation.

        ``sim_day`` is days since the start of the profile's history (docs/14 §2).
        """
        rows = self.coached.get(scenario, {}) if coached else {}
        probs = rows.get(probe) or self.answers[scenario][probe]
        for adaptation in self.adaptations:
            if adaptation.scenario == scenario and adaptation.probe == probe:
                genuine = self.answers[GENUINE_REFERENCE][probe]
                probs = _mix(genuine, probs, adaptation.weight(sim_day))
        return probs

    def sample_answer(
        self,
        rng: np.random.Generator,
        scenario: ScenarioType,
        probe: str,
        *,
        coached: bool = False,
        sim_day: float = 0.0,
    ) -> str:
        probs = self.answer_probs(scenario, probe, coached=coached, sim_day=sim_day)
        index = int(rng.choice(len(probs), p=np.asarray(probs, dtype=np.float64)))
        return self.outcomes[probe][index]


def load_response_models(
    generated: Path = GENERATED_FILE, config_path: Path = CONFIG_FILE
) -> ResponseModels:
    """Read the committed freeze and the switches in the hand-written config."""
    config = load_config(config_path)
    data = yaml.safe_load(generated.read_text(encoding="utf-8"))

    def rows(section: Mapping[str, Mapping[str, list[float]]]) -> dict[ScenarioType, Any]:
        return {
            ScenarioType(s): {k: tuple(float(p) for p in v) for k, v in r.items()}
            for s, r in section.items()
        }

    return ResponseModels(
        outcomes={k: tuple(v) for k, v in data["outcomes"].items()},
        answers=rows(data["answers"]),
        coached=rows(data["coached"]),
        telemetry_targets=config.telemetry_targets,
        coached_share=config.coached_victims.share,
        adaptations=config.coaching_adaptation,
    )


# --------------------------------------------------------------------------- telemetry


@dataclass(frozen=True, slots=True)
class SignalDraw:
    """Which telemetry-driven passive signals a session shows (docs/14 §5.1)."""

    on_call_unknown_number: bool
    remote_access_active: bool
    paste_or_long_dwell: bool
    cadence_mismatch: bool


def draw_signals(rng: np.random.Generator, targets: TelemetryTargets) -> SignalDraw:
    """Independent draws at the target rates. The scenario generator turns them into
    ``session_telemetry`` values that the classifiers (docs/08 §5) read back."""
    u = rng.random(4)
    return SignalDraw(
        on_call_unknown_number=bool(u[0] < targets.on_call_unknown_number),
        remote_access_active=bool(u[1] < targets.remote_access_active),
        paste_or_long_dwell=bool(u[2] < targets.paste_or_long_dwell),
        cadence_mismatch=bool(u[3] < targets.cadence_mismatch),
    )
